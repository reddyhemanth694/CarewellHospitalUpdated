
package com.controller;

import java.io.IOException;

import jakarta.servlet.ServletException;
import jakarta.servlet.annotation.WebServlet;
import jakarta.servlet.http.Cookie;
import jakarta.servlet.http.HttpServlet;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import jakarta.servlet.http.HttpSession;

import com.dao.UserDAO;
import com.daoimpl.UserDAOImpl;
import com.model.User;
import com.util.PasswordUtil;

@WebServlet("/login")
public class LoginController extends HttpServlet {

    private static final long serialVersionUID = 1L;

    /* "Keep me signed in" keeps the session alive for 7 days. */
    private static final int REMEMBER_ME_SECONDS = 7 * 24 * 60 * 60;

    private UserDAO userDAO;

    @Override
    public void init() throws ServletException {
        userDAO = new UserDAOImpl();
    }

    @Override
    protected void doPost(HttpServletRequest request,
                          HttpServletResponse response)
            throws ServletException, IOException {

        String email = request.getParameter("email");
        String password = request.getParameter("password");

        // Keep the booking page the visitor came from (only safe values).
        String nextPage = safeNext(request.getParameter("next"));
        String nextQuery = nextPage.isEmpty() ? ""
                : "&next=" + java.net.URLEncoder.encode(
                        nextPage, java.nio.charset.StandardCharsets.UTF_8);


        if (email == null || email.isBlank()
                || password == null || password.isEmpty()) {
            response.sendRedirect(
                    request.getContextPath() + "/login.jsp?error=invalid" + nextQuery);
            return;
        }

        User user = userDAO.getUserByEmail(email.trim());

        if (user == null
                || !"ACTIVE".equalsIgnoreCase(user.getStatus())
                || user.getPassword() == null) {

            response.sendRedirect(
                    request.getContextPath() + "/login.jsp?error=invalid" + nextQuery);
            return;
        }

        String storedPassword = user.getPassword();
        boolean passwordMatches;

        // BCrypt hashes generated by PasswordUtil begin with "$2a$".
        if (storedPassword.startsWith("$2a$")) {

            passwordMatches =
                    PasswordUtil.verifyPassword(password, storedPassword);

        } else {

            // Legacy account: verify the existing plaintext password.
            passwordMatches = storedPassword.equals(password);

            // Upgrade a legacy password after successful verification.
            if (passwordMatches) {
                String hashedPassword = PasswordUtil.hashPassword(password);

                if (!userDAO.updatePassword(
                        user.getUserId(), hashedPassword)) {

                    response.sendRedirect(
                            request.getContextPath()
                            + "/login.jsp?error=loginFailed");
                    return;
                }

                System.out.println(
                        "Password migration completed for user ID: "
                        + user.getUserId());

                user.setPassword(hashedPassword);
            }
        }

        if (!passwordMatches) {
            response.sendRedirect(
                    request.getContextPath() + "/login.jsp?error=invalid" + nextQuery);
            return;
        }

        String role = user.getRole();

        if (role == null
                || (!"ADMIN".equalsIgnoreCase(role)
                && !"DOCTOR".equalsIgnoreCase(role)
                && !"PATIENT".equalsIgnoreCase(role))) {

            response.sendRedirect(
                    request.getContextPath() + "/login.jsp?error=invalidRole");
            return;
        }

        // Never keep the password or password hash in the session object.
        user.setPassword(null);

        HttpSession oldSession = request.getSession(false);

        if (oldSession != null) {
            oldSession.invalidate();
        }

        HttpSession session = request.getSession(true);
        request.changeSessionId();

        session.setAttribute("user", user);
        session.setAttribute("userId", user.getUserId());
        session.setAttribute("role", role);

        if ("true".equals(request.getParameter("remember"))) {
            session.setMaxInactiveInterval(REMEMBER_ME_SECONDS);

            // Make the session cookie survive a browser restart.
            Cookie sessionCookie = new Cookie("JSESSIONID", session.getId());
            sessionCookie.setMaxAge(REMEMBER_ME_SECONDS);
            sessionCookie.setHttpOnly(true);
            sessionCookie.setSecure(isHttps(request));
            String cookiePath = request.getContextPath();
            sessionCookie.setPath(cookiePath.isEmpty() ? "/" : cookiePath);
            response.addCookie(sessionCookie);
        }

        if ("ADMIN".equalsIgnoreCase(role)) {

            response.sendRedirect(
                    request.getContextPath() + "/admin/dashboard.jsp");

        } else if ("DOCTOR".equalsIgnoreCase(role)) {

            response.sendRedirect(
                    request.getContextPath() + "/doctor/dashboard.jsp");

        } else if (!nextPage.isEmpty()) {

            // Patient clicked "Book" on the home page before signing in.
            response.sendRedirect(request.getContextPath() + nextPage);

        } else {

            response.sendRedirect(
                    request.getContextPath() + "/patient/dashboard.jsp");
        }
    }

    /* Only allow redirects to the patient booking page (prevents open redirects). */
    private static String safeNext(String next) {
        if (next == null) {
            return "";
        }
        next = next.trim();
        if (!next.startsWith("/patient/book-appointment.jsp")
                || next.contains("//") || next.contains("\\")
                || next.contains("\r") || next.contains("\n")) {
            return "";
        }
        return next;
    }

    /* Render sits behind a proxy, so also check X-Forwarded-Proto. */
    private static boolean isHttps(HttpServletRequest request) {
        return request.isSecure()
                || "https".equalsIgnoreCase(request.getHeader("X-Forwarded-Proto"));
    }

    @Override
    protected void doGet(HttpServletRequest request,
                         HttpServletResponse response)
            throws ServletException, IOException {

        response.sendRedirect(
                request.getContextPath() + "/login.jsp");
    }
}
